-- Para cambiarlo después (en el SQL Editor):  select definir_codigo_alta('MI-CODIGO-NUEVO');
create or replace function definir_codigo_alta(p_codigo text) returns void
language plpgsql security definer set search_path = public as $$
begin
  if length(trim(coalesce(p_codigo, ''))) < 8 then raise exception 'El código de alta debe tener al menos 8 caracteres'; end if;
  update plataforma set codigo_alta = extensions.crypt(trim(p_codigo), extensions.gen_salt('bf')), cambiado_en = now() where id = 1;
end $$;
revoke all on function definir_codigo_alta(text) from public, anon, authenticated;

create or replace function validar_codigo_alta(p_codigo text) returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from plataforma
                 where codigo_alta = extensions.crypt(trim(coalesce(p_codigo, '')), codigo_alta))
$$;

-- Negocio dueño de un código de registro (null si no coincide)
create or replace function negocio_por_codigo(p_codigo text) returns integer
language sql stable security definer set search_path = public as $$
  select r.negocio_id from registro_admin r join tienda t on t.id = r.negocio_id
   where t.activo and r.codigo_hash = extensions.crypt(trim(coalesce(p_codigo, '')), r.codigo_hash)
   limit 1
$$;
revoke all on function negocio_por_codigo(text) from public, anon, authenticated;

create or replace function validar_codigo_registro(p_codigo text) returns boolean
language sql stable security definer set search_path = public as $$
  select negocio_por_codigo(p_codigo) is not null
$$;

create or replace function definir_codigo_registro(p_codigo text) returns void
language plpgsql security definer set search_path = public as $$
declare v_neg integer := mi_negocio(); v_otro integer;
begin
  if not es_admin() or v_neg is null then raise exception 'Solo un administrador puede cambiar el código de registro'; end if;
  if length(trim(coalesce(p_codigo, ''))) < 6 then raise exception 'El código debe tener al menos 6 caracteres'; end if;
  v_otro := negocio_por_codigo(p_codigo);
  if (v_otro is not null and v_otro <> v_neg) or validar_codigo_alta(p_codigo) then
    raise exception 'Ese código no está disponible. Escribe otro';
  end if;
  insert into registro_admin (negocio_id, codigo_hash, cambiado_en, cambiado_por)
  values (v_neg, extensions.crypt(trim(p_codigo), extensions.gen_salt('bf')), now(), auth.uid())
  on conflict (negocio_id) do update set codigo_hash = excluded.codigo_hash, cambiado_en = now(), cambiado_por = auth.uid();
  perform registrar_actividad('registro.codigo_cambiado', 'registro_admin', v_neg::text, null);
end $$;

-- Otro administrador para un negocio que ya existe
create or replace function registrar_administrador(p_nombre text, p_codigo text, p_telefono text default null)
returns void
language plpgsql security definer set search_path = public as $$
declare v_correo text; v_neg integer;
begin
  if auth.uid() is null then raise exception 'Inicia sesión para completar el registro'; end if;
  if exists (select 1 from perfiles where id = auth.uid()) then raise exception 'Esta cuenta ya tiene un perfil'; end if;
  if coalesce(trim(p_nombre), '') = '' then raise exception 'Escribe tu nombre'; end if;
  v_neg := negocio_por_codigo(p_codigo);
  if v_neg is null then raise exception 'El código de registro no es correcto'; end if;
  select email into v_correo from auth.users where id = auth.uid();
  insert into perfiles (id, negocio_id, nombre, correo, telefono, rol)
  values (auth.uid(), v_neg, trim(p_nombre), lower(v_correo), nullif(trim(coalesce(p_telefono, '')), ''), 'admin');
  perform registrar_actividad('registro.administrador', 'perfiles', auth.uid()::text, jsonb_build_object('correo', v_correo));
end $$;

-- Negocio nuevo con su primer administrador
create or replace function registrar_negocio(p_nombre text, p_negocio text, p_codigo_alta text,
                                             p_telefono text default null, p_nit text default null)
returns integer
language plpgsql security definer set search_path = public as $$
declare v_correo text; v_neg integer;
begin
  if auth.uid() is null then raise exception 'Inicia sesión para completar el registro'; end if;
  if exists (select 1 from perfiles where id = auth.uid()) then raise exception 'Esta cuenta ya tiene un perfil'; end if;
  if coalesce(trim(p_nombre), '') = '' then raise exception 'Escribe tu nombre'; end if;
  if length(trim(coalesce(p_negocio, ''))) < 2 then raise exception 'Escribe el nombre del negocio'; end if;
  if not validar_codigo_alta(p_codigo_alta) then raise exception 'El código de alta no es correcto'; end if;
  select email into v_correo from auth.users where id = auth.uid();

  insert into tienda (nombre, nit, telefono, correo)
  values (trim(p_negocio), nullif(trim(coalesce(p_nit, '')), ''), nullif(trim(coalesce(p_telefono, '')), ''), lower(v_correo))
  returning id into v_neg;

  insert into perfiles (id, negocio_id, nombre, correo, telefono, rol)
  values (auth.uid(), v_neg, trim(p_nombre), lower(v_correo), nullif(trim(coalesce(p_telefono, '')), ''), 'admin');

  insert into categorias (negocio_id, nombre)
  select v_neg, c from unnest(array['Celulares','Computadores','Accesorios','Televisores','Gaming',
                                    'Fundas','Cargadores','Cables','Audífonos','Protectores']) c;

  perform registrar_actividad('registro.negocio', 'tienda', v_neg::text,
          jsonb_build_object('negocio', trim(p_negocio), 'correo', v_correo));
  return v_neg;
end $$;

