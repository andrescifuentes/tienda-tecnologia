create or replace function carpeta_de_mi_negocio(p_nombre text) returns boolean
language sql stable security definer set search_path = public as $$
  select mi_negocio() is not null and (
    (storage.foldername(p_nombre))[1] = 'negocio-' || mi_negocio()
    -- archivos anteriores a este script (fotos en la raíz, PDF en carpetas por año)
    or (mi_negocio() = 1 and coalesce((storage.foldername(p_nombre))[1], '') !~ '^negocio-')
  )
$$;
revoke all on function carpeta_de_mi_negocio(text) from public, anon;
grant execute on function carpeta_de_mi_negocio(text) to authenticated;

