do $$
declare t text;
begin
  foreach t in array array['categorias','proveedores','productos','unidades_serializadas',
                           'movimientos_inventario','compras','clientes','facturas',
                           'garantias','movimientos','actividad'] loop
    execute format('alter table %I add column if not exists negocio_id integer references tienda(id)', t);
    -- carga sin disparar auditoría ni bloqueos de historial
    execute format('alter table %I disable trigger user', t);
    execute format('update %I set negocio_id = 1 where negocio_id is null', t);
    execute format('alter table %I enable trigger user', t);
    execute format('alter table %I alter column negocio_id set default mi_negocio()', t);
    if t <> 'actividad' then
      execute format('alter table %I alter column negocio_id set not null', t);
    end if;
    execute format('create index if not exists %I on %I (negocio_id)', 'idx_' || t || '_negocio', t);
  end loop;
end $$;
create index if not exists idx_perfiles_negocio on perfiles (negocio_id);

-- Nadie mueve filas de un negocio a otro
create or replace function negocio_inmutable() returns trigger
language plpgsql as $$
begin
  if new.negocio_id is distinct from old.negocio_id then
    raise exception 'No se puede cambiar el negocio de un registro';
  end if;
  return new;
end $$;
do $$
declare t text;
begin
  foreach t in array array['perfiles','categorias','proveedores','productos','unidades_serializadas',
                           'compras','clientes','facturas','garantias','movimientos'] loop
    execute format('drop trigger if exists trg_negocio_inmutable on %I', t);
    execute format('create trigger trg_negocio_inmutable before update of negocio_id on %I
                    for each row execute function negocio_inmutable()', t);
  end loop;
end $$;

