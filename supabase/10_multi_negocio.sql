create or replace function mi_negocio() returns integer
language sql stable security definer set search_path = public as $$
  select negocio_id from perfiles where id = auth.uid() and activo
$$;
revoke all on function mi_negocio() from public, anon;
grant execute on function mi_negocio() to authenticated, service_role;

-- Los vendedores que crea el administrador (función crear-empleado, sin
-- sesión) quedan en el negocio de quien los creó.
create or replace function perfiles_fijar_negocio() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.negocio_id is null then
    new.negocio_id := coalesce(mi_negocio(), (select negocio_id from perfiles where id = new.creado_por));
  end if;
  if new.negocio_id is null then
    raise exception 'El perfil necesita un negocio';
  end if;
  return new;
end $$;
drop trigger if exists trg_perfiles_negocio on perfiles;
create trigger trg_perfiles_negocio before insert on perfiles
  for each row execute function perfiles_fijar_negocio();

-- ---------------------------------------------------------------------
-- 3. negocio_id en las tablas del negocio (lo existente queda en el 1)
