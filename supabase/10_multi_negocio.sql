-- Los datos sensibles del negocio no se cambian desde la app
create or replace function tienda_guard() returns trigger
language plpgsql as $$
begin
  -- Solo cuando la app actualiza directamente (las funciones del servidor sí pueden)
  if current_user in ('authenticated', 'anon') then
    new.id := old.id;
    new.ultimo_numero_factura := old.ultimo_numero_factura;
    new.activo := old.activo;
    new.creado_en := old.creado_en;
  end if;
  return new;
end $$;
drop trigger if exists trg_tienda_guard on tienda;
create trigger trg_tienda_guard before update on tienda
  for each row execute function tienda_guard();

