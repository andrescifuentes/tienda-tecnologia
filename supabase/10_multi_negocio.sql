  if (select data_type from information_schema.columns
       where table_schema = 'public' and table_name = 'tienda' and column_name = 'id') = 'smallint' then
    alter table tienda alter column id type integer;
  end if;
  if (select is_identity from information_schema.columns
       where table_schema = 'public' and table_name = 'tienda' and column_name = 'id') = 'NO' then
    alter table tienda alter column id drop default;
    alter table tienda alter column id add generated by default as identity;
  end if;
end $$;
select setval(pg_get_serial_sequence('tienda', 'id'), greatest((select max(id) from tienda), 1));

alter table tienda
  add column if not exists activo    boolean not null default true,
  add column if not exists logo_url  text,
