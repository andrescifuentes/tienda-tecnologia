--  ANTES: saca un respaldo (Database > Backups, o Table Editor > Export).
--
--  Qué hace:
--  1. Cada fila de la tabla "tienda" pasa a ser un NEGOCIO. Angie Tech es
--     el negocio 1 y todo lo que existe hoy queda en él (no se pierde nada).
--  2. Todas las tablas del negocio llevan "negocio_id". Supabase solo deja
--     ver y modificar las filas del negocio de quien inició sesión, aunque
--     alguien manipule la app.
--  3. Los códigos de producto, documentos de cliente, categorías, seriales
--     y números de factura pasan a ser únicos POR NEGOCIO. Cada negocio
--     lleva su propio consecutivo de facturas.
--  4. Las funciones de venta, compra, devolución, anulación, ajustes y el
--     tablero validan que todo pertenezca al mismo negocio.
--  5. Registro:
--     - Negocio nuevo: se crea con el CÓDIGO DE ALTA (solo lo tienes tú).
--     - Otro administrador de un negocio existente: usa el código de
--       registro de ESE negocio (Más > Configuración).
--     - Vendedores: los crea el administrador dentro de su negocio.
--  6. Archivos: las fotos y los PDF nuevos se guardan en la carpeta
--     "negocio-<id>"; los archivos actuales siguen siendo de Angie Tech.
--
--  Se puede ejecutar más de una vez. Si algo falla, no se aplica nada.
--  NO ejecutes después los scripts 05, 06 y 07 sin adaptarlos: fueron
--  escritos para una sola tienda.
